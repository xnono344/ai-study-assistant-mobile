export async function loadStoredLanguage() {
  try {
    const stored = await SecureStore.getItemAsync(LANG_KEY);
    if (stored && ['en', 'fr', 'ar'].includes(stored)) {
      await i18n.changeLanguage(stored);
      if (stored === 'ar' && !I18nManager.isRTL) {
        I18nManager.forceRTL(true);
      } else if (stored !== 'ar' && I18nManager.isRTL) {
        I18nManager.forceRTL(false);
      }
    }
  } catch {}
}

export async function setLanguage(lng: 'en' | 'fr' | 'ar') {
  await i18n.changeLanguage(lng);
  await SecureStore.setItemAsync(LANG_KEY, lng);
  if (lng === 'ar' && !I18nManager.isRTL) {
    I18nManager.forceRTL(true);
  } else if (lng !== 'ar' && I18nManager.isRTL) {
    I18nManager.forceRTL(false);
  }
}

